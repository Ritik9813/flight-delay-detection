"""Train, evaluate, select and save the flight-delay models.

Workflow
1. Load and validate data/flights_500.csv.
2. Stratified 80/20 train/test split.
3. Compare Logistic Regression, Random Forest and Gradient Boosting.
   Selection criterion: highest mean 5-fold cross-validated F1 on the TRAINING
   set. The test set is used only to report final metrics (no selection leakage).
4. Fit a separate regressor for delay minutes (target clipped at 0, so early
   departures count as 0 minutes of delay and predictions are non-negative).
5. Save the fitted pipelines (joblib) and metrics/feature info (JSON).

Usage:
    python train_model.py
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import (
    GradientBoostingClassifier, GradientBoostingRegressor, RandomForestClassifier,
)
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_validate, train_test_split

from src.config import (
    CATEGORICAL_FEATURES, DATA_PATH, DECISION_THRESHOLD, DEFAULT_RISK_THRESHOLDS,
    DELAY_THRESHOLD_MIN, INPUT_FEATURE_COLUMNS, LEAKAGE_COLUMNS, METRICS_PATH,
    MODEL_PATH, NUMERIC_FEATURES, RANDOM_STATE, TRAFFIC_LEVELS, WEATHER_CONDITIONS,
)
from src.evaluation import (
    classification_metrics, extract_feature_importance, regression_metrics,
    select_best_model,
)
from src.preprocessing import (
    build_pipeline, clean_training_data, load_dataset, make_xy, time_to_minutes,
)

LIMITATIONS = [
    "Only 500 records: metrics have wide confidence intervals and change noticeably with a different random split.",
    "The bundled dataset is SYNTHETIC. The relationships were written into the generator, so high scores show the model can recover simulated rules, not that it predicts real airline delays.",
    "Test results must not be read as real-world airline performance. Real operations involve crew, maintenance, air-traffic control and cascading effects that are not modelled here.",
    "Predicted probabilities are model estimates, not guarantees, and are not calibrated against real outcomes.",
    "The system is a batch ML predictor, not a live flight tracker: it does not know the current status of any real flight.",
    "Previous_Delay_Min is only valid when the previous leg's delay is known before departure; if left blank the model falls back to median imputation.",
]


def build_candidate_models() -> dict:
    return {
        "Logistic Regression": LogisticRegression(
            max_iter=2000, class_weight="balanced", random_state=RANDOM_STATE
        ),
        "Random Forest": RandomForestClassifier(
            n_estimators=300, min_samples_leaf=3, class_weight="balanced",
            random_state=RANDOM_STATE, n_jobs=-1,
        ),
        "Gradient Boosting": GradientBoostingClassifier(
            n_estimators=150, learning_rate=0.05, max_depth=3, subsample=0.8,
            random_state=RANDOM_STATE,
        ),
    }


def _minutes_to_hhmm(minutes: float) -> str:
    return f"{int(minutes // 60):02d}:{int(minutes % 60):02d}"


def compute_baselines(X_train: pd.DataFrame) -> dict:
    """Typical-flight reference values used by the per-prediction explanation."""
    baselines = {
        col: float(X_train[col].median())
        for col in ("Distance_km", "Temperature_C", "Wind_Speed_kmh", "Visibility_km", "Previous_Delay_Min")
    }
    for col in ("Weather_Condition", "Traffic_Level", "Airline"):
        baselines[col] = str(X_train[col].mode().iloc[0])
    baselines["Scheduled_Departure"] = _minutes_to_hhmm(float(time_to_minutes(X_train["Scheduled_Departure"]).median()))
    return baselines


def train_and_save(
    data_path=DATA_PATH,
    model_path=MODEL_PATH,
    metrics_path=METRICS_PATH,
    test_size: float = 0.2,
    cv_folds: int = 5,
    verbose: bool = True,
    dataset_note: str = "Synthetic dataset generated by generate_dataset.py (not real airline data).",
) -> dict:
    log = print if verbose else (lambda *a, **k: None)

    raw = load_dataset(data_path)
    clean, report = clean_training_data(raw)
    X, y, delay_minutes = make_xy(clean)
    if y.nunique() < 2:
        raise ValueError("The dataset contains only one class; at least one delayed and one on-time flight are required.")
    min_class = int(y.value_counts().min())
    if min_class < 2:
        raise ValueError("Each class needs at least 2 flights for a stratified split.")
    log(f"Loaded {report['rows_in']} rows -> {report['rows_out']} usable. "
        f"Delayed: {int(y.sum())} ({y.mean():.1%})")

    X_train, X_test, y_train, y_test, d_train, d_test = train_test_split(
        X, y, delay_minutes, test_size=test_size, stratify=y, random_state=RANDOM_STATE
    )
    folds = max(2, min(cv_folds, int(y_train.value_counts().min())))
    cv = StratifiedKFold(n_splits=folds, shuffle=True, random_state=RANDOM_STATE)

    results: dict = {}
    fitted: dict = {}
    for name, estimator in build_candidate_models().items():
        pipeline = build_pipeline(estimator)
        cv_scores = cross_validate(pipeline, X_train, y_train, cv=cv, scoring=["f1", "roc_auc"], n_jobs=1)
        pipeline.fit(X_train, y_train)
        proba = pipeline.predict_proba(X_test)[:, 1]
        pred = (proba >= DECISION_THRESHOLD).astype(int)
        results[name] = {
            "cv_f1_mean": float(np.mean(cv_scores["test_f1"])),
            "cv_f1_std": float(np.std(cv_scores["test_f1"])),
            "cv_roc_auc_mean": float(np.mean(cv_scores["test_roc_auc"])),
            "test": classification_metrics(y_test, pred, proba),
        }
        fitted[name] = pipeline
        log(f"  {name:<20} CV F1={results[name]['cv_f1_mean']:.3f}  "
            f"test F1={results[name]['test']['f1']:.3f}  test AUC={results[name]['test']['roc_auc']:.3f}")

    best_name = select_best_model(results)
    best_pipeline = fitted[best_name]
    log(f"Selected model: {best_name}")

    # Regression: non-negative delay minutes (early departures -> 0).
    regressor = build_pipeline(GradientBoostingRegressor(
        n_estimators=200, learning_rate=0.05, max_depth=3, subsample=0.8, random_state=RANDOM_STATE
    ))
    regressor.fit(X_train, d_train.clip(lower=0))
    reg_pred = np.clip(regressor.predict(X_test), 0, None)
    reg_true = d_test.clip(lower=0)
    regression = regression_metrics(reg_true, reg_pred)
    baseline_pred = np.full(len(reg_true), float(d_train.clip(lower=0).mean()))
    regression["baseline_mae_predict_mean"] = regression_metrics(reg_true, baseline_pred)["mae"]
    regression["note"] = ("Target is delay minutes clipped at 0 (early departures count as 0); "
                          "predictions are clipped to be non-negative.")
    log(f"Regression  MAE={regression['mae']:.2f} min  RMSE={regression['rmse']:.2f} min")

    categories = {
        "airlines": sorted(X_train["Airline"].dropna().unique().tolist()),
        "origins": sorted(X_train["Origin"].dropna().unique().tolist()),
        "destinations": sorted(X_train["Destination"].dropna().unique().tolist()),
        "weather": WEATHER_CONDITIONS,
        "traffic": TRAFFIC_LEVELS,
    }
    categories["airports"] = sorted(set(categories["origins"]) | set(categories["destinations"]))

    bundle = {
        "classifier": best_pipeline,
        "regressor": regressor,
        "model_name": best_name,
        "decision_threshold": DECISION_THRESHOLD,
        "risk_thresholds": dict(DEFAULT_RISK_THRESHOLDS),
        "delay_threshold_min": DELAY_THRESHOLD_MIN,
        "input_columns": INPUT_FEATURE_COLUMNS,
        "baselines": compute_baselines(X_train),
        "categories": categories,
        "sklearn_version": sklearn.__version__,
        "trained_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }

    metrics = {
        "generated_at": bundle["trained_at"],
        "sklearn_version": sklearn.__version__,
        "random_state": RANDOM_STATE,
        "dataset_note": dataset_note,
        "dataset": {
            **{k: v for k, v in report.items()},
            "delayed": int(y.sum()),
            "on_time": int((y == 0).sum()),
            "delay_rate": float(y.mean()),
            "delay_threshold_min": DELAY_THRESHOLD_MIN,
        },
        "split": {
            "test_size": test_size, "stratified": True,
            "train_rows": int(len(X_train)), "test_rows": int(len(X_test)),
            "cv_folds": folds,
        },
        "selection": {
            "criterion": f"Highest mean {folds}-fold cross-validated F1-score on the training set "
                         "(F1 balances precision and recall, so it is not fooled by class imbalance like accuracy). "
                         "The test set is used only for final reporting.",
            "selected_model": best_name,
            "decision_threshold": DECISION_THRESHOLD,
        },
        "models": results,
        "feature_importance": extract_feature_importance(best_pipeline),
        "regression": regression,
        "features": {
            "input_columns": INPUT_FEATURE_COLUMNS,
            "engineered_numeric": NUMERIC_FEATURES,
            "categorical": CATEGORICAL_FEATURES,
            "excluded_for_leakage": LEAKAGE_COLUMNS,
        },
        "limitations": LIMITATIONS,
    }

    model_path, metrics_path = Path(model_path), Path(metrics_path)
    model_path.parent.mkdir(parents=True, exist_ok=True)
    metrics_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(bundle, model_path)
    metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    log(f"Saved model   -> {model_path}")
    log(f"Saved metrics -> {metrics_path}")
    return metrics


def main() -> None:
    parser = argparse.ArgumentParser(description="Train the flight-delay models.")
    parser.add_argument("--data", type=Path, default=DATA_PATH)
    parser.add_argument("--test-size", type=float, default=0.2)
    args = parser.parse_args()
    try:
        train_and_save(data_path=args.data, test_size=args.test_size)
    except (FileNotFoundError, ValueError) as exc:
        raise SystemExit(f"Training failed: {exc}")


if __name__ == "__main__":
    main()
